// =====================================================================================
// CT: вычисление Ez в узлах сетки
//
// Архитектура (как обсудили):
//   1) compute_cell_ez_and_slopes: по ячейкам (i,j).
//        - считает Ez_cell(i,j) = -(V x B)_z в центре ячейки
//        - для ВЕРХНЕЙ h-грани(i,j+1) и ПРАВОЙ v-грани(i+1,j) этой ячейки считает
//          по 2 производные Ez вдоль грани (к обоим её концам == 2 узлам)
//        - каждая производная кладётся в свой персональный "слот" узла,
//          так что разные ячейки пишут в РАЗНЫЕ ячейки памяти (нет гонки записи).
//        - HLL-взвешивание делается сразу здесь же, но только по паре (эта
//          ячейка, соседняя ячейка через эту грань), т.к. обе стороны производной
//          (Ez_cell и Ez на смежной грани) у пары ячеек, использующих одну и ту же
//          физическую грань, между собой отличаются лишь тем, что расположены по
//          разные стороны от грани. Чтобы получить HLL-смесь для КОНКРЕТНОЙ грани,
//          нужно видеть Ez_cell обеих ячеек, прилежащих к ней. Это удобно сделать
//          через shared-память (halo в 1 ячейку), см. ниже.
//
//   2) assemble_node_ez: по узлам (i,j), i=0..N, j=0..M.
//        - складывает 4 слота (по одному от каждой из 4-х ячеек, окружающих узел)
//        - делит на число реально существующих вкладов (для граничных узлов
//          часть слотов отсутствует физически, см. ниже про границы)
//
// Слоты на узел (4 шт, по одному "владельцу"-ячейке каждый):
//   node(i,j) окружают ячейки (i-1,j-1), (i,j-1), (i-1,j), (i,j)
//   т.к. в терминологии задачи "каждая ячейка считает только верх и право":
//     - ячейка (i-1,j-1) отдаёт производную вдоль СВОЕЙ верхней h-грани к её
//       ПРАВОМУ концу  -> это узел (i, j)          [slot_h_from_left]
//     - ячейка (i,j-1)   отдаёт производную вдоль СВОЕЙ верхней h-грани к её
//       ЛЕВОМУ концу   -> это тоже узел (i, j)      [slot_h_from_right]
//     - ячейка (i-1,j-1) отдаёт производную вдоль СВОЕЙ правой v-грани к её
//       ВЕРХНЕМУ концу -> узел (i, j)               [slot_v_from_below]
//     - ячейка (i-1,j)   отдаёт производную вдоль СВОЕЙ правой v-грани к её
//       НИЖНЕМУ концу  -> узел (i, j)               [slot_v_from_above]
//
//   Итого 4 слота на узел: {h_from_left, h_from_right, v_from_below, v_from_above}
//   Хранятся в 4 отдельных плоских массивах размера (N+1)*(M+1).
//
// !!! МЕСТА-ЗАГЛУШКИ, ПОМЕЧЕННЫЕ "TODO(user)" — геометрия (шаги по r/phi,
//     касательные компоненты tau1/tau2, знаки Ez=-(V x B)) — оставлены вам,
//     т.к. у вас полярная геометрия и я не хочу гадать за вас.
// =====================================================================================


// ----------------------------------------------------------------------------
// Индексация массивов (примите/поправьте под свою систему):
//   Ez_cell      : размер N*M,        idx = j*N + i
//   h_Ez, h_SL,h_SR : размер N*(M+1), idx = j*N + i      (h-грань (i,j))
//   v_Ez, v_SL,v_SR : размер (N+1)*M, idx = j*(N+1) + i  (v-грань (i,j))
//   node-слоты   : размер (N+1)*(M+1), idx = j*(N+1) + i (узел (i,j))
//   Ez_node (итог): размер (N+1)*(M+1), тот же idx
// ----------------------------------------------------------------------------

__device__ __forceinline__ int idx_cell(int i, int j) { return j * N + i; }
__device__ __forceinline__ int idx_hface(int i, int j) { return j * N + i; }         // N x (M+1)
__device__ __forceinline__ int idx_vface(int i, int j) { return j * (N + 1) + i; }    // (N+1) x M
__device__ __forceinline__ int idx_node(int i, int j) { return j * (N + 1) + i; }     // (N+1) x (M+1)


// ----------------------------------------------------------------------------
// HLL-смешивание производной (или любой величины типа "поток") по аналогии с HLL:
//   d_L, d_R  — значения производной, посчитанные "со стороны L" и "со стороны R"
//               грани (т.е. из двух ячеек, прилежащих к этой грани)
//   SL, SR    — крайние характеристики HLL на этой грани
// ----------------------------------------------------------------------------
__device__ __forceinline__ double hll_blend(double d_L, double d_R, double SL, double SR)
{
    if (SL >= 0.0) return d_L;
    if (SR <= 0.0) return d_R;
    return (SR * d_L - SL * d_R) / (SR - SL);
    // TODO(user): проверьте знаки/порядок d_L, d_R относительно того, как вы
    // определяете "левое"/"правое" состояние в самом HLLDQ_Korolkov, чтобы
    // соглашение о знаках SL/SR было согласовано (обычно SL<0<SR, "L" -- это
    // состояние с меньшим индексом координаты, что у вас и есть).
}


// ----------------------------------------------------------------------------
// Ez в центре ячейки: Ez = -(V x B)_z
// TODO(user): у вас полярная геометрия (r, phi) в плоскости (x,y) — если Vx,Vy,
// Bx,By уже декартовы компоненты (как в первом ядре), то формула ниже верна
// без изменений, т.к. (V x B)_z инвариантна к повороту системы координат в
// плоскости xy. Если же где-то Bz/Vz участвуют иначе — поправьте.
// ----------------------------------------------------------------------------
__device__ __forceinline__ double compute_Ez_cell(double Vx, double Vy, double Bx, double By)
{
    return -(Vx * By - Vy * Bx);
}


// =====================================================================================
// Kernel 1: по ячейкам. Считает Ez_cell, и для ВЕРХНЕЙ h-грани и ПРАВОЙ v-грани
// этой ячейки — по 2 производные (к обоим концам грани), с HLL-смешиванием.
//
// Для HLL-смешивания на грани нужен Ez_cell СОСЕДНЕЙ ячейки через эту грань —
// поэтому используем shared-память с halo = 1 ячейка (только имя halo, не 2 как
// в первом ядре, тут расчёт куда проще).
// =====================================================================================

#define SLOPE_BX 16   // TODO(user): согласуйте с реальным блоком запуска
#define SLOPE_BY 16
#define SLOPE_SHARED_I (SLOPE_BX + 2)   // +1 halo слева, +1 halo справа
#define SLOPE_SHARED_J (SLOPE_BY + 2)   // +1 halo снизу, +1 halo сверху

__global__ void compute_cell_ez_and_slopes(
    const double* Vx, const double* Vy, const double* Bx, const double* By,
    double* Ez_cell,                          // выход: N*M, тоже нужен снаружи (например для диагностики)
    const double* h_Ez, const double* h_SL, const double* h_SR,   // грани, N x (M+1)
    const double* v_Ez, const double* v_SL, const double* v_SR,   // грани, (N+1) x M
    double* slot_h_from_left,   // (N+1)x(M+1), пишет ячейка (i,j) в узел (i+1, j+1)
    double* slot_h_from_right,  // (N+1)x(M+1), пишет ячейка (i,j) в узел (i,   j+1)
    double* slot_v_from_below,  // (N+1)x(M+1), пишет ячейка (i,j) в узел (i+1, j+1)
    double* slot_v_from_above,  // (N+1)x(M+1), пишет ячейка (i,j) в узел (i+1, j)
    const double* dx_arr,       // TODO(user): шаг по x/r для каждой ячейки-грани (см. ниже)
    const double* dy_arr        // TODO(user): шаг по y/phi для каждой ячейки-грани (см. ниже)
)
{
    __shared__ double sh_Ez[SLOPE_SHARED_I][SLOPE_SHARED_J];

    int tx = threadIdx.x;
    int ty = threadIdx.y;
    int i_start = blockIdx.x * SLOPE_BX;
    int j_start = blockIdx.y * SLOPE_BY;

    int i = i_start + tx;
    int j = j_start + ty;

    // --- 1. Каждый поток считает Ez_cell для СВОЕЙ ячейки (включая один halo-слой) ---
    // Загружаем блок (SLOPE_BX+2) x (SLOPE_BY+2) ячеек Ez_cell в shared.
    {
        int total_load = SLOPE_SHARED_I * SLOPE_SHARED_J;
        int tid = tx + ty * SLOPE_BX;
        for (int k = tid; k < total_load; k += SLOPE_BX * SLOPE_BY)
        {
            int il = k / SLOPE_SHARED_J;
            int jl = k % SLOPE_SHARED_J;
            int ig = i_start - 1 + il;
            int jg = j_start - 1 + jl;

            double ez;
            if (ig >= 0 && ig < N && jg >= 0 && jg < M)
            {
                ez = compute_Ez_cell(Vx[idx_cell(ig, jg)], Vy[idx_cell(ig, jg)],
                                      Bx[idx_cell(ig, jg)], By[idx_cell(ig, jg)]);
            }
            else
            {
                // TODO(user): граничная экстраполяция Ez_cell за пределы сетки.
                // Пока делаем простой clamp к ближайшей внутренней ячейке —
                // замените на то, что физически соответствует вашим ГУ
                // (возможно, для i<0 нужно явное ГУ через rho_in/V_phi_init и т.п.,
                // как это сделано в compute_fluxes для i==0).
                int ic = min(max(ig, 0), N - 1);
                int jc = min(max(jg, 0), M - 1);
                ez = compute_Ez_cell(Vx[idx_cell(ic, jc)], Vy[idx_cell(ic, jc)],
                                      Bx[idx_cell(ic, jc)], By[idx_cell(ic, jc)]);
            }
            sh_Ez[il][jl] = ez;
        }
    }
    __syncthreads();

    if (i >= N || j >= M) return;

    int il = tx + 1;  // локальный индекс своей ячейки в shared (с учётом halo=1)
    int jl = ty + 1;

    double ez_here  = sh_Ez[il][jl];
    double ez_right = sh_Ez[il + 1][jl];   // сосед справа (i+1, j)
    double ez_up    = sh_Ez[il][jl + 1];   // сосед сверху (i, j+1)

    // Записываем Ez_cell в выходной массив (пригодится для отладки/других нужд)
    Ez_cell[idx_cell(i, j)] = ez_here;

    // ---------------------------------------------------------------------
    // A) ВЕРХНЯЯ h-грань этой ячейки = h-грань(i, j+1)
    //    Она также является нижней h-гранью соседней ячейки (i, j+1).
    //    Производная "снизу" (из этой ячейки, (i,j)):
    //        d_below = (Ez(h-грань(i,j+1)) - Ez_cell(i,j)) / dy_up
    //    Производная "сверху" (из ячейки (i,j+1), приходится считать её здесь
    //        же, т.к. её Ez_cell у нас в shared):
    //        d_above = (Ez_cell(i,j+1) - Ez(h-грань(i,j+1))) / dy_up_neighbor
    //    HLL-смешивание по SL,SR ЭТОЙ h-грани дает итоговую производную вдоль
    //    грани, которую разносим к обоим концам (левому и правому узлам).
    // ---------------------------------------------------------------------
    {
        int hf = idx_hface(i, j + 1);           // верхняя h-грань этой ячейки
        double ez_face = h_Ez[hf];
        double SL = h_SL[hf];
        double SR = h_SR[hf];

        // TODO(user): корректные шаги. Если сетка неравномерная по r (в случае
        // h-граней шаг вдоль r, т.к. грань горизонтальна по phi, идём по r?..
        // ВНИМАНИЕ: разберитесь, что тут на самом деле должно быть — расстояние
        // от центра ячейки (i,j) до грани (i,j+1) (по phi, т.е. DPHI/2 * r) и
        // расстояние от центра ячейки (i,j+1) до той же грани.
        double dy_this = dx_arr[idx_cell(i, j)];      // ПЛЕЙСХОЛДЕР — замените
        double dy_neighbor = dy_arr[idx_cell(i, j)];  // ПЛЕЙСХОЛДЕР — замените

        double d_below = (ez_face - ez_here) / dy_this;
        double d_above = (ez_up - ez_face) / dy_neighbor;

        double d_blend = hll_blend(d_below, d_above, SL, SR);
        // TODO(user): проверьте соответствие "L/R" в hll_blend направлению SL/SR
        // как их отдаёт HLLDQ_Korolkov для этой грани (у вас "L"= ячейка с
        // меньшим j, "R" = с большим j — так же, как для потоков массы и т.п.)

        // TODO(user): формула сноса производной вдоль грани к узлу — обычно это
        //   Ez_node_contribution = Ez_face ± 0.5 * d_blend * (шаг вдоль грани)/2
        // т.е. нужен шаг ВДОЛЬ грани (не поперёк!), которым мы только что не
        // пользовались — тут нужен явный вами заданный шаг по x (для h-грани)
        // между центром грани и узлом. Ниже — общая форма, подставьте шаг сами:
        double dx_half = 0.5 * dx_arr[idx_hface(i, j + 1)]; // ПЛЕЙСХОЛДЕР

        double contrib_left  = ez_face - d_blend * dx_half; // к левому концу грани = узел (i,   j+1)
        double contrib_right = ez_face + d_blend * dx_half; // к правому концу грани = узел (i+1, j+1)

        slot_h_from_right[idx_node(i,     j + 1)] = contrib_left;   // эта ячейка "владеет" вкладом в левый узел своей верхней грани
        slot_h_from_left [idx_node(i + 1, j + 1)] = contrib_right;  // и в правый узел тоже
    }

    // ---------------------------------------------------------------------
    // B) ПРАВАЯ v-грань этой ячейки = v-грань(i+1, j)
    //    Аналогично A), но вдоль y/phi, снос к нижнему/верхнему узлам этой
    //    грани: узел (i+1, j) и узел (i+1, j+1).
    // ---------------------------------------------------------------------
    {
        int vf = idx_vface(i + 1, j);
        double ez_face = v_Ez[vf];
        double SL = v_SL[vf];
        double SR = v_SR[vf];

        double dx_this = dy_arr[idx_cell(i, j)];      // ПЛЕЙСХОЛДЕР — замените (шаг по x/r до грани)
        double dx_neighbor = dx_arr[idx_cell(i, j)];  // ПЛЕЙСХОЛДЕР — замените

        double d_left  = (ez_face - ez_here)  / dx_this;
        double d_right = (ez_right - ez_face) / dx_neighbor;

        double d_blend = hll_blend(d_left, d_right, SL, SR);
        // TODO(user): опять же сверьте ориентацию L/R с HLLDQ_Korolkov для v-граней

        double dy_half = 0.5 * dy_arr[idx_vface(i + 1, j)]; // ПЛЕЙСХОЛДЕР, шаг вдоль грани (по y/phi)

        double contrib_below = ez_face - d_blend * dy_half; // к нижнему концу = узел (i+1, j)
        double contrib_above = ez_face + d_blend * dy_half; // к верхнему концу = узел (i+1, j+1)

        slot_v_from_above[idx_node(i + 1, j    )] = contrib_below; // эта ячейка владеет вкладом снизу в нижний узел
        slot_v_from_below[idx_node(i + 1, j + 1)] = contrib_above;
    }

    // ---------------------------------------------------------------------
    // Граничные грани, которые НИКЕМ не считаются автоматически:
    //   - нижняя h-грань (j==0): её "верхний сосед" - ячейка (i,0) сама же,
    //     а "нижний сосед" не существует (граница). Обрабатывается отдельно.
    //   - левая v-грань (i==0): аналогично.
    // TODO(user): обработать j==0 и i==0 отдельными блоками ниже, скорее
    // всего снося ГУ (заданные для грани, как вы говорили — среднее между
    // двумя гранями узла на границе). Я оставляю структуру, но не гадаю
    // за вас формулы ГУ.
    // ---------------------------------------------------------------------
    if (j == 0)
    {
        // TODO(user): нижняя граница по j — если это ось симметрии (как в
        // compute_fluxes для j==0/j==M-1 видно, что там зеркальные условия),
        // то, возможно, нижняя h-грань (i,0) — тоже физическая грань, а не
        // "снаружи сетки", и её нужно обработать так же, как блок A) выше,
        // но с ez_up, замененным на зеркальное значение. Решите сами по
        // аналогии с тем, как в compute_fluxes строится симметрия для j==0.
    }

    if (i == 0)
    {
        // TODO(user): левая граница (i==0) — это, по всей видимости, ваша
        // "физическая" внутренняя граница (rho_in, V_phi_init и т.п.), не
        // периодическая и не симметричная. Нужно решить, как здесь считать
        // Ez_node на грани (i=0 столбец узлов): либо явно из заданных на
        // границе V,B (как вы предложили — "снести скорость и магнитное
        // поле и явно посчитать Ez"), либо взять из v_Ez на грани (i=0) без
        // производной вообще (d=0), что тоже разумное упрощение для старта.
    }
}


// =====================================================================================
// Kernel 2: по узлам (i,j), i=0..N, j=0..M.
// Складывает 4 слота в финальный Ez_node.
//
// Для внутренних узлов все 4 слота заполнены. Для граничных узлов часть
// слотов не была заполнена ни одной ячейкой (см. TODO выше) — там нужно либо
// заранее проинициализировать слоты как "invalid"/NaN и отдельно посчитать
// среднее по факту доступных, либо (проще и надёжнее) отдельно заполнить
// недостающие слоты в специальном проходе по границе перед этим ядром.
//
// Ниже — самый простой вариант: считаем, что ВСЕ 4 слота для ВСЕХ узлов,
// включая граничные, кем-то заполнены (внутренними ячейками + вашей
// доработкой граничных случаев выше). Тогда сборка тривиальна:
// =====================================================================================

__global__ void assemble_node_ez(
    const double* slot_h_from_left,
    const double* slot_h_from_right,
    const double* slot_v_from_below,
    const double* slot_v_from_above,
    double* Ez_node   // (N+1) x (M+1)
)
{
    int i = blockIdx.x * blockDim.x + threadIdx.x;
    int j = blockIdx.y * blockDim.y + threadIdx.y;

    if (i > N || j > M) return;

    int nd = idx_node(i, j);

    double sum = slot_h_from_left[nd] + slot_h_from_right[nd]
               + slot_v_from_below[nd] + slot_v_from_above[nd];

    Ez_node[nd] = 0.25 * sum;

    // TODO(user): если для каких-то граничных узлов физически участвуют не
    // все 4 грани (например, угол расчётной области), тут нужно делить не
    // на 4, а на фактическое число вкладов. Проще всего это сделать, заранее
    // проставив в неиспользуемые слоты те же значения, что и в соседний
    // валидный слот (дублирование вместо честного веса), либо передать сюда
    // маску/счётчик валидных вкладов на узел.
}
